/**
 * Drift gate for the vendored permission catalogue.
 *
 * WHY THIS FILE EXISTS. Eight frontend suites read the backend's RBAC catalogue
 * out of a SIBLING checkout. CI clones one repository, so every one of them
 * either threw at module load or returned before asserting anything — measured
 * on run 33719474880: 9 failed suites, 8 of them this cause. The page-level RBAC
 * gate had therefore never been enforced in CI at all.
 *
 * The facts are now vendored as `contracts/permission-catalog.json`, following
 * the `contracts/openapi.json` precedent. A vendored copy that silently goes
 * stale is WORSE than no copy, because it turns "the backend renamed a key" into
 * a green run. So this gate is the load-bearing half, and it has three rules,
 * two of which need nothing but this repository:
 *
 *   1. WELL-FORMED (hermetic). Floors and shape. An empty, truncated or
 *      hand-edited artifact cannot satisfy the suites' "a silent empty sweep
 *      cannot pass" assertions if it cannot get past this.
 *   2. AGREES WITH THE API CONTRACT (hermetic). Every `x-permission` an
 *      operation declares in `contracts/openapi.json` must appear in the
 *      catalogue. openapi.json is generated by the same backend and is already
 *      byte-compared by `check:contract-vendor`, so it is an INDEPENDENT witness
 *      that lives in this repository. This is what makes the drift check
 *      actually run in a frontend-only CI job rather than being permanently
 *      inconclusive: it catches the dangerous direction — a route requiring a
 *      permission the vendored catalogue has never heard of.
 *   3. BYTE-IDENTICAL TO A FRESH REGENERATION (needs the backend). The complete
 *      check. Where the backend is not beside this repo it is reported NOT RUN
 *      and the run ends INCONCLUSIVE (exit 2); STREAMLINE_ALLOW_FRONTEND_ONLY=1
 *      downgrades that to a labelled PARTIAL (exit 0) with rules 1 and 2 still
 *      blocking. It is never silently skipped.
 *
 * Flags:
 *   --self-test   Internal assertions over synthetic inputs, both directions.
 */

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  backendAvailable,
  backendUnreachableReason,
  reportBackendUnreachable,
} from "./check-repo-paths.mjs";
import {
  buildCatalog,
  extractDelegableModuleIds,
  extractMemberDefaultPermissions,
  extractOwnerOnlyOperations,
  extractPermissionNames,
  isPermissionKey,
  openApiPermissions,
  serializeCatalog,
} from "./permission-catalog-extract.mjs";
import { readBackendCatalog } from "./generate-permission-catalog.mjs";

const FRONTEND_ROOT = fileURLToPath(new URL("..", import.meta.url));
const CATALOG_PATH = join(FRONTEND_ROOT, "contracts", "permission-catalog.json");
const OPENAPI_PATH = join(FRONTEND_ROOT, "contracts", "openapi.json");

const FLOORS = {
  permissions: 400,
  delegableModuleIds: 5,
  memberDefaultPermissions: 20,
  ownerOnlyOperations: 1,
};

function isSortedUnique(values) {
  for (let i = 1; i < values.length; i += 1) if (values[i - 1] >= values[i]) return false;
  return true;
}

/** Rule 1. Returns a list of failures; empty means well-formed. */
export function wellFormedFailures(catalog) {
  const failures = [];
  for (const field of ["permissions", "delegableModuleIds", "memberDefaultPermissions"]) {
    const values = catalog[field];
    if (!Array.isArray(values)) {
      failures.push(`${field} is not an array`);
      continue;
    }
    if (values.length < FLOORS[field])
      failures.push(`${field}: ${values.length} entries, below the floor of ${FLOORS[field]}`);
    if (!isSortedUnique(values)) failures.push(`${field} is not sorted and unique`);
  }
  const owners = catalog.ownerOnlyOperations;
  if (owners === null || typeof owners !== "object" || Array.isArray(owners))
    failures.push("ownerOnlyOperations is not an object");
  else if (Object.keys(owners).length < FLOORS.ownerOnlyOperations)
    failures.push("ownerOnlyOperations is empty");

  if (Array.isArray(catalog.permissions)) {
    const malformed = catalog.permissions.filter((name) => !isPermissionKey(name));
    if (malformed.length > 0)
      failures.push(`permissions contains ${malformed.length} malformed key(s): ${malformed.slice(0, 5).join(", ")}`);
  }
  if (Array.isArray(catalog.memberDefaultPermissions) && Array.isArray(catalog.permissions)) {
    const known = new Set(catalog.permissions);
    const orphans = catalog.memberDefaultPermissions.filter((name) => !known.has(name));
    if (orphans.length > 0)
      failures.push(`memberDefaultPermissions has ${orphans.length} key(s) absent from permissions: ${orphans.slice(0, 5).join(", ")}`);
  }
  return failures;
}

/** Rule 2. Every route-bound permission in the vendored API contract is catalogued. */
export function contractAgreementFailures(catalog, openApiDocument) {
  const declared = new Set(catalog.permissions ?? []);
  const bound = openApiPermissions(openApiDocument);
  if (bound.length === 0) return ["the vendored OpenAPI contract declares no x-permission at all"];
  return bound
    .filter((name) => !declared.has(name))
    .map((name) => `x-permission "${name}" is bound to an operation but is not in the catalogue`);
}

function runSelfTest() {
  let passed = 0;
  const failures = [];
  const assert = (label, condition) => {
    if (condition) passed += 1;
    else failures.push(label);
  };

  const permissionSource = [
    "export const HR: Permission[] = [",
    "  {",
    '    name: "hr:leaves:view",',
    '    resource: "hr:leaves",',
    "  },",
    "  {",
    '    name: "hr:leaves:manage",',
    "  },",
    "  {",
    "    name: `hr:${dynamic}:view`,",
    "  },",
    "];",
  ].join("\n");
  const names = extractPermissionNames(permissionSource);
  assert("literal permission names are extracted", names.includes("hr:leaves:view"));
  assert("a template-literal name is skipped, not half-recorded", names.length === 2);

  const registrySource = `
    { id: "hr", ladder: "delegable" },
    { id: "platform", ladder: "owner-only" },
    { id: "crm", ladder: "delegable" },`;
  const delegable = extractDelegableModuleIds(registrySource);
  assert("delegable module ids are extracted", delegable.includes("hr") && delegable.includes("crm"));
  assert("a non-delegable ladder is excluded", !delegable.includes("platform"));

  const roleDefaults = `
    export const MEMBER_DEFAULTS = ["self:profile:view", "chat:messages:send"];
    export const ROLE_DEFAULT_PERMISSIONS = { HR_ADMIN: ["hr:employees:manage"] };`;
  const memberDefaults = extractMemberDefaultPermissions(roleDefaults);
  assert("member defaults come from above the role map", memberDefaults.includes("self:profile:view"));
  assert(
    "keys that only a non-member role holds are NOT read as member defaults",
    !memberDefaults.includes("hr:employees:manage"),
  );

  const ownerOnly = extractOwnerOnlyOperations(
    `{ "org.delete": { risk: "high", reason: "Destroys the tenant." } }`,
  );
  assert("owner-only ids map to their reason", ownerOnly["org.delete"] === "Destroys the tenant.");

  const catalog = buildCatalog({
    permissionSources: [permissionSource],
    moduleRegistrySource: registrySource,
    roleDefaultsSource: roleDefaults,
    ownerOnlyOperationsSource: `{ "org.delete": { reason: "Destroys the tenant." } }`,
  });
  assert(
    "generated module-access keys are folded in",
    catalog.permissions.includes("hr:access:view") && catalog.permissions.includes("crm:access:manage"),
  );
  assert("the artifact is sorted and unique", isSortedUnique(catalog.permissions));
  assert(
    "serialisation is stable, so byte-for-byte is a meaningful claim",
    serializeCatalog(catalog) === serializeCatalog(buildCatalog({
      permissionSources: [permissionSource],
      moduleRegistrySource: registrySource,
      roleDefaultsSource: roleDefaults,
      ownerOnlyOperationsSource: `{ "org.delete": { reason: "Destroys the tenant." } }`,
    })),
  );

  const healthy = {
    permissions: Array.from({ length: 500 }, (_, i) => `m${String(i).padStart(4, "0")}:a:view`).sort(),
    delegableModuleIds: ["a", "b", "c", "d", "e", "f"],
    memberDefaultPermissions: [],
    ownerOnlyOperations: { "org.delete": "reason" },
  };
  healthy.memberDefaultPermissions = healthy.permissions.slice(0, 25);
  assert("a healthy artifact is well-formed", wellFormedFailures(healthy).length === 0);
  assert(
    "an EMPTY catalogue is rejected — the silent-empty-sweep defect",
    wellFormedFailures({ ...healthy, permissions: [] }).length > 0,
  );
  assert(
    "an UNSORTED catalogue is rejected",
    wellFormedFailures({ ...healthy, delegableModuleIds: ["f", "a", "b", "c", "d", "e"] }).length > 0,
  );
  assert(
    "a DUPLICATED entry is rejected",
    wellFormedFailures({ ...healthy, delegableModuleIds: ["a", "a", "b", "c", "d", "e"] }).length > 0,
  );
  assert(
    "a member default with no catalogue entry is rejected",
    wellFormedFailures({ ...healthy, memberDefaultPermissions: ["ghost:key:view"] }).length > 0,
  );

  const doc = { paths: { "/hr/leaves": { get: { "x-permission": "hr:leaves:view" } } } };
  assert("x-permission is read out of an operation", openApiPermissions(doc)[0] === "hr:leaves:view");
  assert(
    "a catalogue covering the contract agrees with it",
    contractAgreementFailures({ permissions: ["hr:leaves:view"] }, doc).length === 0,
  );
  assert(
    "a STALE catalogue missing a route-bound permission is caught WITHOUT the backend",
    contractAgreementFailures({ permissions: ["hr:leaves:manage"] }, doc).length === 1,
  );
  assert(
    "a contract that declares no permission at all is treated as a broken scan",
    contractAgreementFailures(healthy, { paths: {} }).length === 1,
  );

  if (failures.length > 0) {
    for (const label of failures) console.error(`  FAIL: ${label}`);
    console.error(`check-permission-catalog self-tests: ${failures.length} failed, ${passed} passed`);
    process.exit(1);
  }
  console.log(`check-permission-catalog self-tests: ${passed} passed`);
  process.exit(0);
}

function main() {
  if (!existsSync(CATALOG_PATH)) {
    console.error(
      "contracts/permission-catalog.json is missing. Run `pnpm generate:permission-catalog` with the backend checked out beside this repository and commit the result.",
    );
    process.exit(1);
  }

  const vendored = readFileSync(CATALOG_PATH, "utf8");
  let catalog;
  try {
    catalog = JSON.parse(vendored);
  } catch (error) {
    console.error(`contracts/permission-catalog.json is not valid JSON: ${String(error)}`);
    process.exit(1);
  }

  let failed = false;

  const shape = wellFormedFailures(catalog);
  if (shape.length > 0) {
    console.error("Rule 1 — the vendored catalogue is not well-formed:");
    for (const reason of shape) console.error(`  ${reason}`);
    failed = true;
  } else {
    console.log(
      `Rule 1 — well-formed: ${catalog.permissions.length} permissions, ${catalog.delegableModuleIds.length} delegable modules, ` +
        `${catalog.memberDefaultPermissions.length} member defaults, ${Object.keys(catalog.ownerOnlyOperations).length} owner-only operations.`,
    );
  }

  if (!existsSync(OPENAPI_PATH)) {
    console.error("Rule 2 — contracts/openapi.json is missing; the hermetic cross-check cannot run.");
    failed = true;
  } else {
    const disagreements = contractAgreementFailures(catalog, JSON.parse(readFileSync(OPENAPI_PATH, "utf8")));
    if (disagreements.length > 0) {
      console.error(`Rule 2 — the vendored catalogue disagrees with the vendored API contract (${disagreements.length}):`);
      for (const reason of disagreements.slice(0, 25)) console.error(`  ${reason}`);
      console.error("  Regenerate with `pnpm generate:permission-catalog` and commit the result.");
      failed = true;
    } else {
      const bound = openApiPermissions(JSON.parse(readFileSync(OPENAPI_PATH, "utf8"))).length;
      console.log(`Rule 2 — every one of the ${bound} route-bound permissions in contracts/openapi.json is catalogued.`);
    }
  }

  if (!backendAvailable) {
    if (failed) {
      console.error(`Rule 3 — NOT RUN. ${backendUnreachableReason()}`);
      process.exit(1);
    }
    reportBackendUnreachable(
      "check-permission-catalog",
      "rule 3 (byte-for-byte regeneration against the backend)",
    );
    return;
  }

  const regenerated = serializeCatalog(readBackendCatalog());
  if (regenerated !== vendored) {
    console.error("Rule 3 — DRIFT: contracts/permission-catalog.json is not what the backend produces now.");
    console.error("  Run `pnpm generate:permission-catalog` and commit the result.");
    const fresh = JSON.parse(regenerated);
    const added = fresh.permissions.filter((name) => !catalog.permissions.includes(name));
    const removed = catalog.permissions.filter((name) => !fresh.permissions.includes(name));
    if (added.length > 0) console.error(`  backend has ${added.length} permission(s) the vendored copy lacks: ${added.slice(0, 10).join(", ")}`);
    if (removed.length > 0) console.error(`  vendored copy has ${removed.length} permission(s) the backend no longer declares: ${removed.slice(0, 10).join(", ")}`);
    failed = true;
  } else {
    console.log("Rule 3 — byte-identical to a fresh regeneration from the backend.");
  }

  if (failed) process.exit(1);
  console.log("\nPermission catalogue: vendored copy is current.");
}

if (process.argv.includes("--self-test")) runSelfTest();
else main();
